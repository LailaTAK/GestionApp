    private void btnRechercheActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRechercheActionPerformed
        // TODO add your handling code here:
    String motCle = txtRecherche.getText().trim();
    
    javax.swing.table.DefaultTableModel model = 
        new javax.swing.table.DefaultTableModel(
            new String[]{"ID", "Nom", "Prénom", "Email", "Téléphone"}, 0
        );
    
    EtudiantDAO dao = new EtudiantDAO();
    java.util.List<String[]> liste;
    
    if (motCle.isEmpty()) {
        liste = dao.lireTous();
    } else {
        liste = dao.rechercher(motCle);
    }
    
    if (liste.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Aucun étudiant trouvé !",
            "Résultat",
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }
    
    for (String[] etudiant : liste) {
        model.addRow(etudiant);
    }
    
    tableEtudiants.setModel(model);
        
    }//GEN-LAST:event_btnRechercheActionPerformed

