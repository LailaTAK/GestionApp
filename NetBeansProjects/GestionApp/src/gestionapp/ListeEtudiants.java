    private void btnSupprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSupprimerActionPerformed
        // TODO add your handling code here:
        int ligne = tableEtudiants.getSelectedRow();
        if(ligne == -1){
            javax.swing.JOptionPane.showMessageDialog(this,"Sélectionnez un étudiant à supprimer");
            return;
        }
        int id = Integer.parseInt(tableEtudiants.getValueAt(ligne,0).toString());
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Confirmer la suppression?", "Attention", javax.swing.JOptionPane.YES_OPTION);
        
        if(confirm == javax.swing.JOptionPane.YES_OPTION){
            EtudiantDAO dao = new EtudiantDAO();
            dao.supprimer(id);
            chargerDonnees();
            NotificationService.afficherNotification("Etudiant supprimé", "L'étudiant a été supprimé de la base !", NotificationService.ERREUR);
        }
    }//GEN-LAST:event_btnSupprimerActionPerformed

