    private void btnExportPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportPDFActionPerformed
        // TODO add your handling code here:
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Enregistrer le PDF");
        fileChooser.setSelectedFile(new java.io.File("liste_etudiants.pdf"));
        
        int userSelection = fileChooser.showSaveDialog(this);
        if(userSelection != javax.swing.JFileChooser.APPROVE_OPTION) return;
        
        String cheminFichier = fileChooser.getSelectedFile().getAbsolutePath();
        if(!cheminFichier.endsWith(".pdf")) cheminFichier += ".pdf";
        
        try{
            com.itextpdf.text.Document document = new com.itextpdf.text.Document();
            com.itextpdf.text.pdf.PdfWriter.getInstance(document, new java.io.FileOutputStream(cheminFichier));
            document.open();
            
            com.itextpdf.text.Font titreFont = new com.itextpdf.text.Font(
               com.itextpdf.text.Font.FontFamily.HELVETICA, 18, 
               com.itextpdf.text.Font.BOLD);
            com.itextpdf.text.Paragraph titre = new com.itextpdf.text.Paragraph(
               "Liste des Etudiants\n\n", titreFont);  
            titre.setAlignment(com.itextpdf.text.Element.ALIGN_CENTER);
            document.add(titre);
            
            com.itextpdf.text.pdf.PdfPTable table = new com.itextpdf.text.pdf.PdfPTable(5);
            table.setWidthPercentage(100);
            table.setWidths(new float[]{1f, 2f, 2f, 3f, 2f});
            
            String[] entetes = {"ID","Nom", "Prenom", "Email","Téléphone"};
            com.itextpdf.text.Font enteteFont = new com.itextpdf.text.Font(com.itextpdf.text.Font.FontFamily.HELVETICA, 12,com.itextpdf.text.Font.BOLD);
            for(String entete : entetes){
                com.itextpdf.text.pdf.PdfPCell cell = new com.itextpdf.text.pdf.PdfPCell(new com.itextpdf.text.Phrase(entete,enteteFont));
                cell.setBackgroundColor(new com.itextpdf.text.BaseColor(52, 152, 219));
                cell.setHorizontalAlignment(com.itextpdf.text.Element.ALIGN_CENTER);
                cell.setPadding(8);
                table.addCell(cell);
            }
            
            EtudiantDAO dao = new EtudiantDAO();
            for(String[] etudiant : dao.lireTous()){
                for(String valeur : etudiant){
                    com.itextpdf.text.pdf.PdfPCell cell = new com.itextpdf.text.pdf.PdfPCell(new com.itextpdf.text.Phrase(valeur != null ? valeur : ""));
                    cell.setPadding(6);
                    table.addCell(cell);
                }
            }
            document.add(table);
            
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("EEEE dd MMMM yyyy 'à' HH:mm", new java.util.Locale("fr", "FR"));
            document.add(new com.itextpdf.text.Paragraph("\nExporté le : " + sdf.format(new java.util.Date())));
            document.close();
            javax.swing.JOptionPane.showMessageDialog(this, "PDF exporté avec succès !\n" + cheminFichier,
            "Export réussi",
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }catch(Exception e){
             javax.swing.JOptionPane.showMessageDialog(this,
            "Erreur lors de l'export : " + e.getMessage(),
            "Erreur",
            javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_btnExportPDFActionPerformed

