    private void remplirComboEtudiants() {
        EtudiantDAO dao = new EtudiantDAO();
        for (String[] e : dao.getEtudiantsPourCombo()){
            cmbEtudiant.addItem(e[0]+ " - "+ e[1]);
        }
    }

    private void remplirComboStatut() {
        cmbStatut.addItem("absent");
        cmbStatut.addItem("présent");
        cmbStatut.addItem("retard");
        cmbStatut.addItem("justifié");
    }

private void chargerAbsences() {
    javax.swing.table.DefaultTableModel model =
        new javax.swing.table.DefaultTableModel(
            new String[]{"ID", "Étudiant", "Date", "Statut", "Motif"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // tableau non éditable
            }
        };
    
    EtudiantDAO dao = new EtudiantDAO();
    java.util.List<String[]> liste = dao.lireAbsences();
    
    System.out.println("Nombre d'absences trouvées : " + liste.size());
    
    for (String[] abs : liste) {
        model.addRow(abs);
    }
    
    tableAbsences.setModel(model);
    tableAbsences.revalidate();
    tableAbsences.repaint();
}

