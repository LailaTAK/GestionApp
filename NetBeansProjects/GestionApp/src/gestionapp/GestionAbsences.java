    private void btnEnregistrerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnregistrerActionPerformed
        // TODO add your handling code here:
        if(cmbEtudiant.getSelectedItem()==null){
            javax.swing.JOptionPane.showMessageDialog(this, "Sélectionnez un étudiant !","Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        String selected = cmbEtudiant.getSelectedItem().toString();
        int etudiantId = Integer.parseInt(selected.split(" - ")[0]);
        
        String date = txtDate.getText().trim();
        String[] statuts = {"absent", "présent", "retard", "justifié"};
int indexStatut = cmbStatut.getSelectedIndex();
String statut = (indexStatut >= 0) ? statuts[indexStatut] : "absent";
System.out.println("Index statut: " + indexStatut + " -> " + statut);
        String motif = txtMotif.getText().trim();
        
        if(date.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this,"La date est obligatoire !","Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        EtudiantDAO dao = new EtudiantDAO();
        System.out.println("=== VALEURS ENVOYÉES ===");
System.out.println("etudiantId = [" + etudiantId + "]");
System.out.println("date = [" + date + "]");
System.out.println("statut = [" + statut + "]");
System.out.println("motif = [" + motif + "]");
        dao.ajouterAbsence(etudiantId, date,statut, motif);
        
        NotificationService.afficherNotification("Absence enregistrée", "L'absence a été enregistrée pour le "+date,NotificationService.AVERTISSEMENT);
        
        txtMotif.setText("");
        chargerAbsences();
    }//GEN-LAST:event_btnEnregistrerActionPerformed

